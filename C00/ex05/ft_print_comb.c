#include <unistd.h>

void	ft_print_comb(void)
{
	char	a[3];

	a[0] = 48;
	a[1] = 49;
	a[2] = 50;
	while (a[0] < 56)
	{
		if (a[0] < a[1] && a[1] < a[2])
		{
			write(1, a, 3);
			if (!(a[0] == 55 && a[1] == 56 && a[2] == 57))
			{
				write(1, ", ", 2);
			}
		}
		if (++a[2] == 58)
		{
			if (++a[1] == 57)
			{
				a[1] = 49;
				a[0]++;
			}
			a[2] = a[1] + 1;
		}
	}
}

int	main(void)
{
	ft_print_comb();
	return (0);
}
