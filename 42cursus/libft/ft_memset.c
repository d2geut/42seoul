#include <stddef.h>

void	*ft_memset(void *ptr, int c, size_t n)
{
	size_t	i;
	char	*a;

	i = 0;
	a = (char *)ptr;
	while (i < n)
	{
		a[i] = c;
		i++;
	}
	return (ptr);
}
