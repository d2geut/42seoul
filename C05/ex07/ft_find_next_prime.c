int	ft_find_next_prime(int nb)
{
	int	i;

	while (1)
	{
		i = 2;
		while (i < nb)
		{
			if (nb % i == 0)
				break;
			i++;
		}
		if (i == nb)
			return (nb);
		nb++;
	}
}
