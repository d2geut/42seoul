#include <unistd.h>

void	wif(char	*a, char	*b)
{
	write(1, a, 2);
	write(1, " ", 1);
	write(1, b, 2);
	if (++b[1] == 58)
	{
		b[1] = 48;
		b[0]++;
	}
	if (b[0] == 58)
	{
		if (++a[1] == 58)
		{
			a[0]++;
			a[1] = 48;
		}
		b[1] = a[1] + 1;
		b[0] = a[0];
		if (b[1] == 58)
		{
			b[1] = 48;
			b[0]++;
		}
	}
}

void	ft_print_comb2(void)
{
	char	a[2];
	char	b[2];

	a[0] = 48;
	a[1] = 48;
	b[0] = 48;
	b[1] = 49;
	while (a[0] < 58)
	{
		wif(a, b);
		if (b[0] == ':')
		{
			break ;
		}
		write(1, ", ", 2);
	}
}
