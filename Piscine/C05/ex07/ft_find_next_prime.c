int	ft_find_next_prime(int nb)
{
	long	i;

	if (nb < 2)
		return (2);
	while (1)
	{
		i = 2;
		while (i * i <= nb)
		{
			if (nb % i == 0)
				break ;
			i++;
		}
		if (i * i > nb)
			return (nb);
		nb++;
	}
}
