#include <unistd.h>

char	*ft_strncat(char *dest, char *src, unsigned int nb)
{
	int				i;
	unsigned int	n;

	i = 0;
	n = 0;
	while (dest[i])
		i++;
	while (n < nb && src[n])
		dest[i++] = src[n++];
	dest[i] = '\0';
	return (dest);
}
