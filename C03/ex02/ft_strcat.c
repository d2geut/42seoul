#include <unistd.h>

char	*ft_strcat(char *dest, char *src)
{
	int	i;
	int	n;

	i = 0;
	n = 0;
	while (dest[i])
		i++;
	while (src[n])
		dest[i++] = src[n++];
	dest[i] = '\0';
	return (dest);
}
