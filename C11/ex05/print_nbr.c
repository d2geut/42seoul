#include "doop.h"

void	print_nbr(long nbr)
{
	char	c;

	if (nbr < 10)
	{
		c = nbr + '0';
		write(1, &c, 1);
	}
	else
	{
		print_nbr(nbr / 10);
		c = nbr % 10 + '0';
		write(1, &c, 1);
	}
}
